/**
 * 房间级规则集（RuleSet）—— 武汉红中赖子杠
 *
 * ⚠️ 设计前提（老吴确认）：**开局口径由房主在建房时选定，每个房间可以不同。**
 * 所以规则不是全局常量，而是一个可实例化的对象：
 *
 *     const rs = createRuleSet('koukou', { cap: 500 });   // 房主选了「口口番」并把封顶调到 500
 *
 * 变化最大的两个轴：
 *   openMode  开口番 / 口口番   —— 影响番数怎么翻倍
 *   wildMode  翻牌定癞（标准）  —— 影响万能牌从哪来
 *              注：红中固定是皮子，绝不当癞子（见 game.deriveWild）
 *
 * 其余细项都留了开关，方便按实际打法微调，不用改引擎代码。
 */

export const RULE_PRESETS = {
  /** 开口番：所有开口只算一次翻倍，四番起胡 */
  kaikou: {
    label: '开口番',
    openMode: 'kaikou',
    minFanSmall: 6,
    minFanBig: 3,
    skinCountLabel: '十一皮四癞',
  },
  /** 口口番：每开一次口翻一倍，六番起胡（2006 腾讯武汉麻将大赛用的就是这版） */
  koukou: {
    label: '口口番',
    openMode: 'koukou',
    minFanSmall: 6,
    minFanBig: 3,
    skinCountLabel: '十一皮四癞',
  },
};

/**
 * 创建一个规则集
 * @param {'kaikou'|'koukou'} preset 预设名
 * @param {object} overrides 覆盖项
 * @returns {object} ruleset
 */
export function createRuleSet(preset = 'koukou', overrides = {}) {
  const base = RULE_PRESETS[preset];
  if (!base) throw new Error(`未知预设: ${preset}`);

  const rs = {
    ...DEFAULTS,
    preset,
    label: base.label,
    openMode: base.openMode,
    minFanSmall: base.minFanSmall,
    minFanBig: base.minFanBig,
    skinCountLabel: base.skinCountLabel,
    ...overrides,
    // ⚠️ `fan` 必须在 `...overrides` **之后**做深合并，否则会被 `overrides.fan` 整体替换 ——
    //    例：createRuleSet('koukou', { fan: { smallHuBase: 1 } }) 会把 dealer/selfDraw/
    //    hardWin/openOnce/bigHuBase/bigHuExtra 全部抹成 undefined，房主只调一个旋钮却悄悄清零整组番底。
    fan: { ...DEFAULTS.fan, ...(overrides.fan ?? {}) },
  };

  // 响应等待时间必须是正数（毫秒），否则回退默认 8000，
  // 避免 0 / 负数导致牌局瞬间跳过（卡死反向）或永远不超时（真卡死）
  if (!Number.isFinite(rs.claimTimeoutMs) || rs.claimTimeoutMs <= 0) {
    rs.claimTimeoutMs = 8000;
  } else {
    rs.claimTimeoutMs = Math.round(rs.claimTimeoutMs);
  }

  /* 2026-10-17：删除 offlineAbsentMul / offlineDissolveMul / offlineAutoPlay 的校验 ——
     自动托管与自动判离席均已移除，这三个键不再被任何代码读取（保留字段仅为兼容旧
     rule_json、不报错）。真正兜底「响应阶段卡死」的仍是 claimTimeoutMs。 */

  return rs;
}

